import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative, join } from 'node:path';

const output = resolve('dist');

async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collect(path));
    else if (entry.isFile() && entry.name !== 'sw.js' && !entry.name.endsWith('.map')) files.push(path);
  }
  return files;
}

const allFiles = await collect(output);
const isAppAsset = file => {
  const path = relative(output, file).replaceAll('\\', '/');
  return path === 'index.html'
    || path === 'manifest.webmanifest'
    || /^(?:icon|apple-touch-icon)(?:-[^/]+)?\.(?:svg|png|webp|ico)$/.test(path)
    || /^assets\/.+/.test(path);
};
const files = allFiles.filter(isAppAsset).sort();
if (!files.some(file => relative(output, file) === 'index.html')) {
  throw new Error('Build index.html first, then generate the service worker.');
}
const assets = files.map(file => relative(output, file).replaceAll('\\', '/'));
const hash = createHash('sha256');
for (const file of files) {
  hash.update(relative(output, file).replaceAll('\\', '/'));
  hash.update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 12);
const worker = [
  '// Generated by scripts/build-sw.js. Cache only public application files.',
  'const CACHE = "zhijian-app-' + version + '";',
  'const PREFIX = "zhijian-app-";',
  'const FILES = ' + JSON.stringify(assets) + ';',
  'const SCOPE = self.registration.scope;',
  'const URLS = FILES.map(file => new URL(file, SCOPE).href);',
  'const OFFLINE_PAGE = new URL("index.html", SCOPE).href;',
  '',
  'self.addEventListener("install", event => {',
  '  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(URLS)).then(() => self.skipWaiting()));',
  '});',
  '',
  'self.addEventListener("activate", event => {',
  '  event.waitUntil(Promise.all([',
  '    caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE).map(key => caches.delete(key)))),',
  '    self.clients.claim(),',
  '  ]));',
  '});',
  '',
  'self.addEventListener("fetch", event => {',
  '  const request = event.request;',
  '  if (request.method !== "GET") return;',
  '  const url = new URL(request.url);',
  '  if (url.origin !== self.location.origin || !url.href.startsWith(SCOPE)) return;',
  '  if (request.mode === "navigate") {',
  '    event.respondWith(fetch(request).catch(async () => (await caches.match(OFFLINE_PAGE)) || Response.error()));',
  '    return;',
  '  }',
  '  if (!URLS.includes(url.href)) return;',
  '  event.respondWith(caches.match(request, { ignoreSearch: true }).then(cached => cached || fetch(request)));',
  '});',
  '',
].join('\n');
await writeFile(join(output, 'sw.js'), worker, 'utf8');
console.log('Generated service worker for ' + files.length + ' app files.');
